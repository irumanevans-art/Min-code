package dev.min.agent.spi

/**
 * 定时器的接口（M5 定时调度）：内核只需要「每隔一阵子被叫一下，去看看有没有到点的定时任务」，
 * 至于靠什么叫——桌面是进程内的定时协程，Android 是前台服务的心跳——是宿主的事。
 *
 * 契约故意放得很松，因为 Android 给不了更多：
 *  - **不保证精确时刻**。到点后最迟在下一次回调时触发，间隔多长由实现定（桌面 15 秒，手机随前台服务心跳，大约一分钟）；
 *  - **只在进程活着时工作**。App 被系统杀掉、或没有前台服务在跑时，定时任务不会触发，也不会补跑——不要假装可靠；
 *  - 回调之间不重叠（上一次没返回就不会再叫）；回调里抛的异常实现要吞掉并继续，不能让一次失败停掉整个定时器。
 */
interface Scheduler {
    /** 开始回调 [onTick]；关闭返回的句柄就停 */
    fun start(onTick: suspend () -> Unit): AutoCloseable
}
